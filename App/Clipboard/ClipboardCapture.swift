import AppKit

@MainActor enum ClipboardCapture {
    static let marker = NSPasteboard.PasteboardType("local.fastbudo.clipboard.generated")
    static let ignored = Set(["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", marker.rawValue])
    static func read(_ board: NSPasteboard, includeOwnWrites: Bool = false) throws -> ClipPayload? {
        let items = board.pasteboardItems ?? []
        guard !items.isEmpty, items.count <= 200 else { return nil }
        // 主动贴图允许本应用复制的图片，被动采集仍跳过自身写入以免重复入库。
        let excluded = includeOwnWrites ? ignored.subtracting([marker.rawValue]) : ignored
        guard !items.contains(where: { !Set($0.types.map(\.rawValue)).isDisjoint(with: excluded) }) else { return nil }
        var captured: [[String: Data]] = []
        var total = 0
        for item in items {
            var data: [String: Data] = [:]
            for type in item.types where ClipPayload.allowed.contains(type.rawValue) {
                if let value = item.data(forType: type) {
                    total += value.count
                    guard total <= ClipPayload.maximum else { throw ClipError.tooLarge }
                    data[type.rawValue] = value
                }
            }
            if !data.isEmpty { captured.append(data) }
        }
        guard !captured.isEmpty else { return nil }
        let result = ClipPayload(items: captured)
        try result.validate()
        return result
    }
    /// 仅提交已由 transformed 在后台校验并转换的内容。
    static func write(_ payload: ClipPayload, to board: NSPasteboard) throws {
        let objects = payload.items.map { representations in
            let item = NSPasteboardItem()
            for (type, data) in representations { item.setData(data, forType: NSPasteboard.PasteboardType(type)) }
            item.setData(Data(), forType: marker)
            return item
        }
        board.clearContents()
        guard board.writeObjects(objects) else { throw ClipError.invalid }
    }
}
